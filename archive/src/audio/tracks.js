// 형식: { bpm, beats(루프 길이·박), loop, channels: [{ wave, gain, notes }] }
//   notes: [[시작박, 길이박, midi], ...]  (채널 안에서 시작박 오름차순 — 하단에서 일괄 정렬)
//   wave: 'square' | 'triangle' | 'sawtooth' | 'noise'
//   noise 채널의 midi는 밝기: 90대=하이햇, 60대=스네어, 40대=저역 럼블(파도)

// ---- 패턴 헬퍼 ---------------------------------------------------------

/** 노트 배열을 off 박만큼 뒤로 민 사본 */
const sh = (notes, off) => notes.map(([t, d, m]) => [t + off, d, m]);

/** 노트 조각들 이어붙이기 */
const cat = (...parts) => parts.flat();

/** pat을 span 박 간격으로 times회 반복 */
const rep = (pat, span, times) => {
  const out = [];
  for (let i = 0; i < times; i++) out.push(...sh(pat, span * i));
  return out;
};

/** 아르페지오: tones를 idx 순서대로 step 박 간격, dur 길이로 */
const arp = (off, tones, idx, step, dur) =>
  idx.map((k, i) => [off + i * step, dur, tones[k]]);

/** 화음 스탭: 같은 시각에 여러 음 동시 발음 */
const stab = (t, dur, tones) => tones.map((m) => [t, dur, m]);

